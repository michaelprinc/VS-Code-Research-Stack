#!/usr/bin/env python3
"""Prove where the shipped `extension/worker/uv.lock` came from and what changed since 0.3.6.

Run from the repository root:

    python3 evidence/quality-v0.3.7-2026-11-02/run_lock_provenance.py \
        --uv /tmp/uvs/uv-0.13.6 --base v0.3.6

It takes the lock as 0.3.6 shipped it (the git blob at `--base`), puts it beside the manifest this
release ships, runs `uv lock` with the pinned uv binary, and records:

* the exact line diff between the 0.3.6 lock and the regenerated lock;
* whether the regenerated lock is byte-identical to the lock now packaged in the VSIX;
* whether the resolved dependency set (names, versions, source) is unchanged.

Writes `lock-provenance.json` beside this file.
"""

from __future__ import annotations

import argparse
import datetime
import difflib
import json
import pathlib
import shutil
import subprocess
import sys
import tempfile
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

import lockintegrity  # noqa: E402  (scripts/lockintegrity.py)


def git_blob(revision: str, relative: str) -> str:
    return subprocess.run(
        ["git", "-C", str(ROOT), "show", f"{revision}:{relative}"],
        capture_output=True, text=True, check=True,
    ).stdout


def pins(lock_text: str) -> set[tuple[str, str]]:
    """(name, version) of every third-party entry in a lock given as text."""
    return {
        (lockintegrity.canonical_name(item["name"]), str(item.get("version", "")))
        for item in lockintegrity.lock_document_text(lock_text)["package"]
        if not (isinstance(item.get("source"), dict)
                and any(key in item["source"] for key in lockintegrity.LOCAL_SOURCE_KEYS))
    }


def root_entry(lock_text: str) -> dict:
    document = lockintegrity.lock_document_text(lock_text)
    entry = lockintegrity.root_entry_of(document)
    return {"name": entry.get("name"), "version": entry.get("version"), "revision": document.get("revision")}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--uv", default="/tmp/uvs/uv-0.13.6")
    parser.add_argument("--base", default="v0.3.6", help="revision whose lock is the starting point")
    args = parser.parse_args()

    shipped_lock = (ROOT / "extension" / "worker" / "uv.lock").read_text(encoding="utf-8")
    shipped_pyproject = (ROOT / "extension" / "worker" / "pyproject.toml").read_text(encoding="utf-8")
    old_lock = git_blob(args.base, "extension/worker/uv.lock")
    old_pyproject = git_blob(args.base, "extension/worker/pyproject.toml")

    workspace = pathlib.Path(tempfile.mkdtemp(prefix="research-stack-provenance-"))
    cache = pathlib.Path(tempfile.mkdtemp(prefix="research-stack-provenance-cache-"))
    try:
        project = workspace / "worker"
        project.mkdir()
        # The manifest this release ships, beside the lock 0.3.6 shipped: that is the pair the
        # packaging defect left inconsistent, and this is the command that repairs it.
        (project / "pyproject.toml").write_text(shipped_pyproject, encoding="utf-8")
        (project / "uv.lock").write_text(old_lock, encoding="utf-8")
        result = subprocess.run(
            [args.uv, "lock", "--project", str(project)],
            cwd=project, capture_output=True, text=True, timeout=900,
            env={"PATH": "/usr/bin:/bin", "HOME": str(pathlib.Path.home()), "UV_CACHE_DIR": str(cache)},
        )
        regenerated = (project / "uv.lock").read_text(encoding="utf-8")
    finally:
        shutil.rmtree(workspace, ignore_errors=True)
        shutil.rmtree(cache, ignore_errors=True)

    diff = list(difflib.unified_diff(old_lock.splitlines(), regenerated.splitlines(),
                                     fromfile=f"{args.base}:extension/worker/uv.lock",
                                     tofile="regenerated by uv lock", lineterm=""))
    old_pins = pins(old_lock)
    new_pins = pins(regenerated)
    shipped_pins = pins(shipped_lock)

    document = {
        "generatedAt": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
        "uvBinary": args.uv,
        "uvVersion": subprocess.run([args.uv, "--version"], capture_output=True, text=True).stdout.strip(),
        "uvLockStdout": result.stdout.strip().splitlines(),
        "uvLockStderr": result.stderr.strip().splitlines(),
        "uvLockExit": result.returncode,
        "baseRevision": args.base,
        "baseLockRootEntry": root_entry(old_lock),
        "basePyprojectVersion": tomllib.loads(old_pyproject)["project"]["version"],
        "diffLines": diff,
        "diffAddedLines": sum(1 for line in diff if line.startswith("+") and not line.startswith("+++")),
        "diffRemovedLines": sum(1 for line in diff if line.startswith("-") and not line.startswith("---")),
        "regeneratedMatchesShippedLock": regenerated == shipped_lock,
        "resolvedSetUnchanged": old_pins == new_pins,
        "shippedResolvedSetMatches": new_pins == shipped_pins,
        "resolvedPackageCount": len(new_pins),
        "thirdPartyPinCount": len([name for name in new_pins if name != "research-stack-basic"]),
    }
    out = pathlib.Path(__file__).resolve().parent / "lock-provenance.json"
    out.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    print(f"diff: +{document['diffAddedLines']} / -{document['diffRemovedLines']} lines, "
          f"resolved set unchanged={document['resolvedSetUnchanged']}, "
          f"matches shipped lock={document['regeneratedMatchesShippedLock']}")
    ok = (result.returncode == 0 and document["regeneratedMatchesShippedLock"]
          and document["resolvedSetUnchanged"] and document["shippedResolvedSetMatches"])
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
